void PointLight::SetPosition(const glm::vec3& Position){
    m_Position = Position;
}

void PointLight::SetRotation(const glm::vec3& Rotation){
    m_Rotation = Rotation;
}

void PointLight::SetScale(const glm::vec3& Scale){
    m_Scale = Scale;
}

void PointLight::OnUpdate(Camera& camera, glm::mat4& projection){
    glm::mat4 view = camera.GetViewMatrix();
    auto& light = ShaderLibrary::GetShader("multiple_lights");
    light.Bind();
    m_Model = glm::mat4(1.0f);
    m_Model = glm::translate(m_Model, m_Position);
    m_Model = glm::scale(m_Model, m_Scale);
    m_Model = glm::rotate(m_Model, Camera::RotationAngle, m_Rotation);
    auto cube_shader = ShaderLibrary::GetShader("basic_cube");
    cube_shader.Bind();
    light.Set("view", view);
    light.Set("model", m_Model);
    light.Set("projection", projection);

    Renderer::DrawQuadPrimitive(m_MeshVao);
    light.Unbind();

    cube_shader.Unbind();
}